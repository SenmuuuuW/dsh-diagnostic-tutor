export type DesignText = typeof en

/** Copy for the design-system surfaces in the active language. */
export function useDesignText(): DesignText {
  return useLang() === 'zh' ? zh : en
}

/** Node state label for the knowledge tab. */
export function nodeStateText(state: string, text: DesignText): string {
  switch (state) {
    case 'unconfirmed': return text.nodeStateUnconfirmed
    case 'explained': return text.nodeStateExplained
    case 'practiced': return text.nodeStatePracticed
    case 'checked': return text.nodeStateChecked
    case 'weak': return text.nodeStateWeak
    case 'blocked': return text.nodeStateBlocked
    case 'confirmed': return text.nodeStateConfirmed
    default: return state
  }
}
